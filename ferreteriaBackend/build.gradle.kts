tasks.jacocoTestReport {
    dependsOn(tasks.test)
    classDirectories.setFrom(
        fileTree("build/classes/java/main") { exclude(coverageExclusions) }
    )
    reports {
        xml.required = true
        html.required = true
    }
}

tasks.jacocoTestCoverageVerification {
    classDirectories.setFrom(
        fileTree("build/classes/java/main") { exclude(coverageExclusions) }
    )
    violationRules {
        rule {   // gate global: >= 80% instrucciones
            element = "BUNDLE"
            limit { counter = "INSTRUCTION"; value = "COVEREDRATIO"; minimum = "0.80".toBigDecimal() }
        }
        rule {   // gate estricto donde vive la lógica: >= 85%
            element = "PACKAGE"
            includes = listOf(
                "mx.ferreteria.api.common.i18n",
                "mx.ferreteria.api.common.error",
                "mx.ferreteria.api.common.web"
            )
            limit { counter = "INSTRUCTION"; value = "COVEREDRATIO"; minimum = "0.85".toBigDecimal() }
        }
    }
}

