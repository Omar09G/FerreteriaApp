// ---------------------------------------------------------------------------
// generateMigrations: genera las migraciones Flyway desde los scripts canónicos
// de ../ferreteriaDB (única fuente de verdad del esquema).
//  - Resuelve meta-comandos psql (\connect se elimina, \ir se empata en línea).
//  - V1__base.sql  = 01_base_esquemas + 02_tablas(+vistas_core empalado) 
//  - V2__parametria.sql = 03_parametria + refresh_tokens (backend)
//  - Copia 05_dummy.sql a db/demo (SOLO perfil demo, nunca en migración).
// Los archivos generados se versionan para que la imagen Docker construya sola.
// ---------------------------------------------------------------------------
val dbScriptsDir = rootProject.projectDir.resolve("../ferreteriaDB/scripts")
val migrationSrc = "src/main/resources/db/migration"
val demoSrc = "src/main/resources/db/demo"

tasks.register("generateMigrations") {
    group = "build"
    description = "Genera migraciones Flyway desde ferreteriaDB/scripts (fuente canónica)"
    onlyIf { dbScriptsDir.resolve("01_base_esquemas.sql").exists() }
    doLast {
        fun read(name: String) = dbScriptsDir.resolve(name).readText()
        val header = """
            -- GENERATED by :generateMigrations — NO EDITAR A MANO.
            -- Fuente: ../ferreteriaDB/scripts (canonico). Regenerar con ./gradlew generateMigrations
        """.trimIndent() + "\n"

        // V1: base + tablas (empalando vistas en lugar de \ir) — sin \connect
        // sqlPuro: neutraliza meta-comandos psql EN LINEA (\gexec al final de SELECT)
        fun sqlPuro(texto: String) = texto.lineSequence()
            .map { l ->
                if (Regex("\\\\g(exec|set)?\\s*$").containsMatchIn(l))
                    "-- [generateMigrations] meta-comando psql omitido"
                else l
            }
            .joinToString("\n")
        val base = sqlPuro(read("01_base_esquemas.sql")).lineSequence()
            .filterNot { it.trimStart().startsWith("\\connect") }.joinToString("\n")
        // El bloque condicional de CREATE DATABASE usa \gexec como terminador:
        // bajo Flyway no aplica (ya estamos DENTRO de la BD objetivo) -> se elimina.
        val baseLimpio = base.replace(
            Regex("(?s)SELECT format\\(\\s*'CREATE DATABASE.*?meta-comando psql omitido"),
            "-- [generateMigrations] CREATE DATABASE condicional omitido (Flyway corre dentro de la BD)"
        )
        val tablasLines = read("02_tablas.sql").lines()
        val irIdx = tablasLines.indexOfFirst { it.trimStart().startsWith("\\ir") }
        require(irIdx >= 0) { "02_tablas.sql sin \\ir vistas_core.sql" }
        val v1 = baseLimpio + "\n\n" +
            tablasLines.take(irIdx).joinToString("\n") + "\n" +
            read("vistas_core.sql") + "\n" +
            tablasLines.drop(irIdx + 1).joinToString("\n")
        val migDir = projectDir.resolve(migrationSrc)
        val demoDir = projectDir.resolve(demoSrc)
        migDir.mkdirs()
        demoDir.mkdirs()
        File(migDir, "V1__base.sql").writeText(header + v1)

        // V2: parametría + tabla de refresh tokens propia del backend
        val refreshTokens = """

            -- ------------------------------------------------------------------
            -- Backend: tokens de refresco JWT (rotacion en logout)
            -- ------------------------------------------------------------------
            CREATE TABLE IF NOT EXISTS seg.refresh_tokens (
                refresh_token_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
                usuario_id       INTEGER NOT NULL REFERENCES seg.usuarios(usuario_id) ON DELETE CASCADE,
                token_hash       VARCHAR(100) NOT NULL UNIQUE,
                expires_at       TIMESTAMPTZ NOT NULL,
                revoked_at       TIMESTAMPTZ,
                creado_en        TIMESTAMPTZ NOT NULL DEFAULT now()
            );
            CREATE INDEX IF NOT EXISTS idx_refresh_usuario ON seg.refresh_tokens(usuario_id);
        """.trimIndent()
        File(migDir, "V2__parametria.sql").writeText(header + read("03_parametria.sql") + "\n" + refreshTokens)

        // Demo data SOLO como recurso del perfil demo
        File(demoDir, "05_dummy.sql").writeText(read("05_dummy.sql"))
        println("generateMigrations: V1/V2 + demo generados desde $dbScriptsDir")
    }
}

tasks.processResources { dependsOn("generateMigrations") }

